GROUP_LISTS = {
    "Clinical": CLINICAL_SOURCES,
    "Environmental": ENVIRONMENTAL_SOURCES,
    "Animal": ANIMAL_SOURCES,
    "Unclassified": UNCLASSIFIED_SOURCES,
}

SOURCE_TO_GROUP = {}
for _grp, _items in GROUP_LISTS.items():
    for _s in _items:
        SOURCE_TO_GROUP[_s.strip().lower()] = _grp
        SOURCE_TO_GROUP[norm(_s)] = _grp


def assign_group(value):
    """Return 'Clinical' | 'Environmental' | 'Animal' | 'Unclassified'.

    1. exact match against the curated lists (case/format insensitive)
    2. otherwise fall back to the keyword rules in classify()
    """
    if value is None:
        return FALLBACK
    raw = str(value).strip()
    if raw == "" or raw.lower() in {"nan", "none", "na", "n/a", "(blank)"}:
        return FALLBACK
    hit = SOURCE_TO_GROUP.get(raw.lower())
    if hit:
        return hit
    hit = SOURCE_TO_GROUP.get(norm(raw))
    if hit:
        return hit
    return classify(raw)


